namespace ProtocGenVoltechGrpc.Errors;

/// <summary>
/// エラーの定義ファイルから、エラーコードの定数と、既定の action の一覧を持つ C# のクラスを生成する。
/// </summary>
/// <remarks>
/// 一覧(All)は ErrorPolicyProvider に渡す。基盤の予約エラー(ReservedErrors)は基盤のパッケージが持つ。
/// </remarks>
internal static class ErrorsGenerator
{
    // 生成するクラスが自分で持つメンバーの名前。reason から作る定数名とぶつけない
    private static readonly string[] memberNames = ["Domain", "All"];

    public static string Generate(ErrorsFile file, string csharpNamespace, string className, string sourceName)
    {
        foreach (var entry in file.Errors)
        {
            var name = CSharpNames.ErrorConstantName(entry.Reason);
            if (memberNames.Contains(name) || name == className)
            {
                throw new GeneratorException($"{entry.Reason}: 定数名 {name} が、生成するクラスの名前やメンバーとぶつかる");
            }
        }

        var writer = new CodeWriter();
        writer.Line("// <auto-generated>")
            .Line($"//     protoc-gen-voltech-grpc が {sourceName} から生成した。手で編集しない。")
            .Line("// </auto-generated>")
            .Line("using System.Collections.Generic;")
            .Line("using VolTech.Client;")
            .Line();
        using (writer.Block($"namespace {csharpNamespace}"))
        {
            writer.Summary([$"エラーコード(domain: {file.Domain})。"]);
            using (writer.Block($"public static class {className}"))
            {
                writer.Summary(["エラーの domain(ErrorInfo.domain)。"])
                    .Line($"public const string Domain = \"{file.Domain}\";");
                foreach (var entry in file.Errors)
                {
                    var summary = entry.Description.Split('\n').Select(line => line.TrimEnd('\r')).ToList();
                    if (entry.ClientOnly)
                    {
                        summary.Add("クライアントだけが使う(サーバーは返さない)。");
                    }

                    writer.Line()
                        .Summary(summary)
                        .Line($"public static readonly global::VolTech.Client.ErrorCode {CSharpNames.ErrorConstantName(entry.Reason)} = new(Domain, \"{entry.Reason}\");");
                }

                writer.Line()
                    .Summary(["この domain のエラーと既定の action の一覧。ErrorPolicyProvider に渡す。"])
                    .Line("public static readonly IReadOnlyList<global::VolTech.Client.ErrorDefinition> All = new global::VolTech.Client.ErrorDefinition[]")
                    .Line("{");
                foreach (var entry in file.Errors)
                {
                    writer.Line($"    new global::VolTech.Client.ErrorDefinition({CSharpNames.ErrorConstantName(entry.Reason)}, global::VolTech.Client.ErrorAction.{ActionName(entry.Action)}),");
                }

                writer.Line("};");
            }
        }

        return writer.ToString();
    }

    // stay → Stay(VolTech.Client.ErrorAction の値の名前)
    private static string ActionName(string action)
    {
        return char.ToUpperInvariant(action[0]) + action[1..];
    }
}
