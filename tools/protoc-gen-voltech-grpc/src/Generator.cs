using Google.Protobuf.Compiler;
using Google.Protobuf.Reflection;

namespace ProtocGenVoltechGrpc;

/// <summary>
/// .proto から、ApiCore を通して呼ぶラッパー・RPC のパスの定数・共通レスポンス項目の目印のインターフェースを生成する。
/// </summary>
/// <remarks>
/// .proto のファイルごとに &lt;ファイル名&gt;Api.cs を1つ作る(player.proto → App/V1/PlayerApi.cs)。
/// 生成するものが無いファイルは作らない。
/// </remarks>
internal static class Generator
{
    /// <summary>
    /// 共通レスポンス項目(規約のフィールド名)と、それを持つレスポンスに付ける目印のインターフェースの名前。
    /// </summary>
    private static readonly (string FieldName, string InterfaceName)[] commonResponseFields =
    [
        ("player_diff", "IHasPlayerDiff"),
        ("badges", "IHasBadges"),
        ("notifications", "IHasNotifications"),
    ];

    public static CodeGeneratorResponse Generate(CodeGeneratorRequest request)
    {
        var parameters = GeneratorParameters.Parse(request.Parameter);
        var types = new TypeIndex(request.ProtoFile);
        var commonFields = CommonFieldTypes(request.ProtoFile, types);

        var response = new CodeGeneratorResponse
        {
            SupportedFeatures = (ulong)CodeGeneratorResponse.Types.Feature.Proto3Optional,
        };
        var filesByName = request.ProtoFile.ToDictionary(file => file.Name);
        foreach (var fileName in request.FileToGenerate)
        {
            var file = filesByName[fileName];
            if (!parameters.Includes(file.Package))
            {
                continue;
            }

            var content = GenerateFile(file, types, commonFields);
            if (content != null)
            {
                var path = $"{CSharpNames.Directory(CSharpNames.Namespace(file))}/{CSharpNames.FileBaseName(file)}Api.cs";
                response.File.Add(new CodeGeneratorResponse.Types.File { Name = path, Content = content });
            }
        }

        return response;
    }

    // 生成するものが無ければ null
    private static string? GenerateFile(
        FileDescriptorProto file,
        TypeIndex types,
        IReadOnlyDictionary<string, CommonField> commonFields)
    {
        var interfaces = commonFields.Values.Where(field => types.FileOf(field.TypeProtoName) == file).ToList();
        var partials = file.MessageType
            .Select(message => (Message: message, Interfaces: CommonInterfacesOf(message, commonFields)))
            .Where(entry => entry.Interfaces.Count > 0)
            .ToList();
        if (file.Service.Count == 0 && interfaces.Count == 0 && partials.Count == 0)
        {
            return null;
        }

        var writer = new CodeWriter();
        writer.Line("// <auto-generated>")
            .Line($"//     protoc-gen-voltech-grpc が {file.Name} から生成した。手で編集しない。")
            .Line("// </auto-generated>")
            .Line("using System.Collections.Generic;")
            .Line("using Cysharp.Threading.Tasks;")
            .Line("using Grpc.Core;")
            .Line("using VolTech.Client;")
            .Line();

        using (writer.Block($"namespace {CSharpNames.Namespace(file)}"))
        {
            var first = true;
            void Separate()
            {
                if (!first)
                {
                    writer.Line();
                }

                first = false;
            }

            var comments = new Comments(file);
            for (var i = 0; i < file.Service.Count; i++)
            {
                Separate();
                WriteMethods(writer, file, file.Service[i]);
                writer.Line();
                WriteWrapper(writer, file, i, comments, types);
            }

            foreach (var field in interfaces)
            {
                Separate();
                WriteInterface(writer, field);
            }

            foreach (var (message, messageInterfaces) in partials)
            {
                Separate();
                writer.Line($"public partial class {message.Name} : {string.Join(", ", messageInterfaces)}")
                    .Line("{")
                    .Line("}");
            }
        }

        return writer.ToString();
    }

    // RPC のパス(/app.v1.PlayerService/SignIn)の定数。FakeCallInvoker への登録やログに使う
    private static void WriteMethods(CodeWriter writer, FileDescriptorProto file, ServiceDescriptorProto service)
    {
        writer.Summary([$"{service.Name} の RPC のパス。FakeCallInvoker への登録などに使う。"]);
        using (writer.Block($"public static class {service.Name}Methods"))
        {
            foreach (var method in service.Method)
            {
                writer.Line($"public const string {method.Name} = \"{MethodPath(file, service, method)}\";");
            }
        }
    }

    private static void WriteWrapper(
        CodeWriter writer,
        FileDescriptorProto file,
        int serviceIndex,
        Comments comments,
        TypeIndex types)
    {
        var service = file.Service[serviceIndex];
        var requiresAuth = !ProtoOptions.SkipAuth(service);
        var client = $"{service.Name}.{service.Name}Client";

        writer.Summary([$"{service.Name} を ApiCore を通して呼ぶ。", .. comments.ForService(serviceIndex)]);
        using (writer.Block($"public sealed class {WrapperName(service)}"))
        {
            foreach (var method in service.Method)
            {
                var isTarget = ProtoOptions.IsIdempotencyTarget(method);
                writer.Line($"private static readonly RpcSettings {SettingsField(method)} = new({service.Name}Methods.{method.Name}, " +
                    $"isIdempotencyTarget: {Bool(isTarget)}, requiresAuth: {Bool(requiresAuth)});");
            }

            writer.Line()
                .Line("private readonly ApiCore core;")
                .Line($"private readonly {client} client;")
                .Line()
                .Summary(["ApiCore と、通信に使う CallInvoker を受け取って作る。"]);
            using (writer.Block($"public {WrapperName(service)}(ApiCore core, CallInvoker callInvoker)"))
            {
                writer.Line("this.core = core;")
                    .Line($"client = new {client}(callInvoker);");
            }

            for (var i = 0; i < service.Method.Count; i++)
            {
                var method = service.Method[i];
                if (method.ClientStreaming || method.ServerStreaming)
                {
                    throw new GeneratorException(
                        $"{service.Name}.{method.Name}: ストリーミングの RPC には対応していない(ApiCore は単項の呼び出しだけを扱う)");
                }

                var requestType = types.CSharpName(method.InputType);
                var responseType = types.CSharpName(method.OutputType);
                writer.Line()
                    .Summary(comments.ForMethod(serviceIndex, i))
                    .Line($"public UniTask<ApiResult<{responseType}>> {method.Name}Async(")
                    .Line($"    {requestType} request,")
                    .Line("    IReadOnlyList<global::VolTech.Client.ErrorCode> handledCodes = null,")
                    .Line("    bool notifyActivity = true)")
                    .Line("{");
                writer.Line($"    return core.InvokeAsync(")
                    .Line($"        {SettingsField(method)},")
                    .Line("        client,")
                    .Line("        request,")
                    .Line("        handledCodes,")
                    .Line($"        static (c, r, options) => c.{method.Name}Async(r, options),")
                    .Line("        notifyActivity);")
                    .Line("}");
            }
        }
    }

    private static void WriteInterface(CodeWriter writer, CommonField field)
    {
        writer.Summary([$"共通レスポンス項目 {field.FieldName} を持つレスポンス。反映処理は、この型で判定して読む。"]);
        using (writer.Block($"public interface {field.InterfaceName}"))
        {
            writer.Line($"{field.PropertyType} {CSharpNames.PropertyName(field.FieldName)} {{ get; }}");
        }
    }

    // 共通レスポンス項目のフィールド名ごとに、その型を集める。型が食い違っていたらエラーにする
    private static Dictionary<string, CommonField> CommonFieldTypes(IEnumerable<FileDescriptorProto> files, TypeIndex types)
    {
        var result = new Dictionary<string, CommonField>();
        foreach (var message in files.SelectMany(file => file.MessageType))
        {
            foreach (var (fieldName, interfaceName) in commonResponseFields)
            {
                var field = message.Field.FirstOrDefault(f => f.Name == fieldName);
                if (field == null)
                {
                    continue;
                }

                if (field.Type != FieldDescriptorProto.Types.Type.Message)
                {
                    throw new GeneratorException($"{message.Name}.{fieldName}: 共通レスポンス項目はメッセージ型にする");
                }

                var repeated = field.Label == FieldDescriptorProto.Types.Label.Repeated;
                var elementType = types.CSharpName(field.TypeName);
                var common = new CommonField(
                    fieldName,
                    interfaceName,
                    field.TypeName,
                    repeated ? $"global::Google.Protobuf.Collections.RepeatedField<{elementType}>" : elementType);
                if (result.TryGetValue(fieldName, out var existing) && existing != common)
                {
                    throw new GeneratorException(
                        $"共通レスポンス項目 {fieldName} の型が、メッセージによって違う({existing.PropertyType} と {common.PropertyType})");
                }

                result[fieldName] = common;
            }
        }

        return result;
    }

    private static List<string> CommonInterfacesOf(DescriptorProto message, IReadOnlyDictionary<string, CommonField> commonFields)
    {
        return message.Field
            .Where(field => commonFields.ContainsKey(field.Name))
            .Select(field => commonFields[field.Name].InterfaceName)
            .ToList();
    }

    private static string MethodPath(FileDescriptorProto file, ServiceDescriptorProto service, MethodDescriptorProto method)
    {
        var serviceFullName = file.Package.Length == 0 ? service.Name : $"{file.Package}.{service.Name}";
        return $"/{serviceFullName}/{method.Name}";
    }

    // PlayerService → PlayerApi
    private static string WrapperName(ServiceDescriptorProto service)
    {
        const string suffix = "Service";
        var name = service.Name.EndsWith(suffix, StringComparison.Ordinal) && service.Name.Length > suffix.Length
            ? service.Name[..^suffix.Length]
            : service.Name;
        return name + "Api";
    }

    private static string SettingsField(MethodDescriptorProto method)
    {
        return CSharpNames.CamelCase(method.Name) + "Settings";
    }

    private static string Bool(bool value)
    {
        return value ? "true" : "false";
    }

    private sealed record CommonField(string FieldName, string InterfaceName, string TypeProtoName, string PropertyType);
}
